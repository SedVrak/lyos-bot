#!/bin/bash

# Вимикаємо скрипт негайно, якщо якась команда завершиться помилкою
set -e

# Кольори для красивого виводу статусів
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0;3m' # No Color

echo -e "${BLUE}=== СТАРТ ДЕПЛОЮ БОТА ===${NC}"

# Крок 1. Стягуємо останні зміни з GitHub
echo -e "${YELLOW}[1/4] Стягування свіжого коду з GitHub...${NC}"
git pull origin master

# Крок 2. Збірка Docker-образу
echo -e "${YELLOW}[2/4] Збірка Docker-образу (npm install + npm run build всередині)...${NC}"
# --no-cache гарантує, що якщо ти змінив код, Docker точно все перебілдить
docker compose build --no-cache

# Крок 3. Перезапуск контейнера
echo -e "${YELLOW}[3/4] Перезапуск контейнера бота у фоновому режимі...${NC}"
# -d запускає в фоні, --remove-orphans чистить старі хвости, якщо мінявся конфіг
docker compose up -d --remove-orphans

# Крок 4. Перевірка статусу
echo -e "${YELLOW}[4/4] Перевірка статусу запущених контейнерів...${NC}"
docker compose ps

echo -e "${GREEN}=== ДЕПЛОЙ УСПІШНО ЗАВЕРШЕНО! ===${NC}"
echo -e "${BLUE}Ось останні 10 рядків логів бота (для перевірки підключення до БД):${NC}"
echo "--------------------------------------------------------"
docker compose logs --tail=10
echo "--------------------------------------------------------"